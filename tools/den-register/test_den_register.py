class PageTests(Base):
    def setUp(self):
        super().setUp()
        self.scene = Scene(self)
        self.session = self.scene.session()
        self.server, self.token = serve.make_server(self.session)
        self.port = self.server.server_address[1]
        threading.Thread(target=self.server.serve_forever, daemon=True).start()

    def tearDown(self):
        self.server.shutdown()
        self.server.server_close()
        super().tearDown()

    def request(self, verb, path, body=None, headers=None, token=True):
        connection = http.client.HTTPConnection("127.0.0.1", self.port, timeout=10)
        sent = {"Host": f"127.0.0.1:{self.port}"}
        if token:
            sent["X-Reg-Token"] = self.token
        if body is not None:
            sent["Content-Type"] = "application/json"
        sent.update(headers or {})
        connection.request(verb, path, body=None if body is None else json.dumps(body), headers=sent)
        response = connection.getresponse()
        data = response.read()
        connection.close()
        return response.status, data

    def test_bound_to_loopback_with_token_host_and_origin_checks(self):
        self.assertEqual(self.server.server_address[0], "127.0.0.1")
        self.assertEqual(self.request("GET", "/api/state")[0], 200)
        self.assertEqual(self.request("GET", "/api/state", token=False)[0], 403)
        self.assertEqual(self.request("GET", "/api/state", headers={"X-Reg-Token": "wrong"})[0], 403)
        self.assertEqual(self.request("GET", "/api/state", headers={"Host": "evil.example"})[0], 403)
        self.assertEqual(self.request("GET", "/api/state", headers={"Host": f"localhost:{self.port}"})[0], 403)
        self.assertEqual(self.request("POST", "/api/click", {"id": "p1", "u": 1, "v": 1},
                                      headers={"Origin": "http://evil.example"})[0], 403)
        status, page = self.request("GET", f"/?t={self.token}", token=False)
        self.assertEqual(status, 200)
        self.assertIn(b"den-register", page)

