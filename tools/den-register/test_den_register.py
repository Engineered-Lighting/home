class WorksheetTests(unittest.TestCase):
    def test_template_opens_for_clicking_but_not_for_a_fit(self):
        text = json.dumps(worksheet.template())
        self.assertEqual(len(worksheet.parse(text, need_positions=False)["points"]), 6)
        with self.assertRaises(Refused) as caught:
            worksheet.parse(text)
        self.assertEqual(caught.exception.reason, "worksheet_invalid")

    def test_crlf_and_a_byte_order_mark_read_the_same(self):
        text = json.dumps(synthetic.worksheet(), indent=1)
        plain = worksheet.parse(text.encode("utf-8"))
        windows = worksheet.parse(b"\xef\xbb\xbf" + text.replace("\n", "\r\n").encode("utf-8"))
        self.assertEqual(plain, windows)

    def test_refusals_name_the_problem(self):
        cases = [("measured_by", "someone", "A or B"), ("frame", "scan", "z_up_metric_floor0"),
                 ("camera_id", "den@oak", "camera_id"), ("room_frame", {}, "unknown keys")]
        for key, value, text in cases:
            sheet = synthetic.worksheet()
            sheet[key] = value
            with self.assertRaises(Refused) as caught:
                worksheet.parse(json.dumps(sheet))
            self.assertEqual(caught.exception.reason, "worksheet_invalid")
            self.assertIn(text, caught.exception.detail)
        sheet = synthetic.worksheet()
        sheet["points"][1]["id"] = sheet["points"][0]["id"]
        with self.assertRaises(Refused):
            worksheet.parse(json.dumps(sheet))
        sheet = synthetic.worksheet()
        sheet["points"][0]["room_xyz"] = sheet["points"][0].pop("room_xyz_m")
        with self.assertRaises(Refused):
            worksheet.parse(json.dumps(sheet))


