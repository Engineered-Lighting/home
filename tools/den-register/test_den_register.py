class Scene:
    """A synthetic take plus a working folder, with helpers to click and fit."""

    def __init__(self, test, *, points=None, fit=synthetic.FIT, checks=synthetic.CHECKS, offsets=None, holes=(),
                 meta=None, scan=None, sheet=None, m=None, background_mm=3500, name="take1", ended=None,
                 frames=3, pose=None, background=None):
        self.test, self.m = test, m or closed_method()
        self.tmp = Path(test.tmp.name)
        self.points = points or synthetic.POINTS
        depth, left, self.seen = synthetic.render(self.points, holes=holes, background_mm=background_mm, pose=pose,
                                                  background=background)
        data = synthetic.bundle(meta or synthetic.metadata(), depth, left)
        self.take = synthetic.write_take(self.tmp / name, [data] * frames)
        if ended is not None:
            path = self.take / "take.json"
            take = json.loads(path.read_text(encoding="utf-8"))
            take["ended_unix"] = ended
            path.write_text(json.dumps(take), encoding="utf-8")
        self.work = self.tmp / "work"
        self.work.mkdir(exist_ok=True)
        self.sheet = sheet or synthetic.worksheet(self.points, fit, checks, offsets, scan=scan)
        (self.work / "worksheet.json").write_text(json.dumps(self.sheet), encoding="utf-8")
        (self.work / "camera-calibration.json").write_text(json.dumps(synthetic.calibration_reply()), encoding="utf-8")

    def session(self):
        sheet = worksheet.load(self.work / "worksheet.json", need_positions=False)
        n = register.frame_number(self.take, None, self.work)
        return register.ClickSession(self.work, self.take, n, sheet, self.m)

    def click_all(self, ids=None, shift=None):
        session = self.session()
        for pid in ids or self.seen:
            u, v, _ = self.seen[pid]
            du, dv = (shift or {}).get(pid, (0, 0))
            session.click({"id": pid, "u": round(u + du, 1), "v": round(v + dv, 1)})
        session.done()
        return session

    def fit(self, now=1_800_000_500.0):
        out = io.StringIO()
        code, report = register.run_fit(self.work, self.take, m=self.m, now=lambda: now, out=out)
        self.out = out.getvalue()
        return code, report

    def room_models(self):
        return records.read_jsonl(self.work / "room-model.jsonl", "room_model_unreadable")

    def calibrations(self):
        return records.read_jsonl(self.work / "calibration-records.jsonl", "calibration_records_unreadable")


